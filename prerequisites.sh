# Dépendances système de tri : LibRaw (RAW), libheif (HEIC/HEIF, feature `heif`),
# libjpeg-turbo (JPEG rapide, feature `turbojpeg`). Voir doc/build.md pour le détail.

# Linux Mint 22 / Ubuntu 24.04 et plus récents (libheif >= 1.17 requis)
# sudo apt install libraw-dev libheif-dev libheif-plugin-libde265 libturbojpeg0-dev pkg-config build-essential

# macOS
# brew install libraw libheif jpeg-turbo pkg-config

# Windows (non testé), avec vcpkg
# vcpkg install libraw:x64-windows libheif:x64-windows libjpeg-turbo:x64-windows
